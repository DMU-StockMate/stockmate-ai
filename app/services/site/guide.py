"""사이트(StockMate) 자체에 대한 질문을 알아보고, 답변 근거가 될 안내서를 제공한다.

채팅은 원래 두 갈래였다: 종목이 있으면 뉴스·공시 RAG, 없으면 모델 지식만 쓰는 일반 답변.
"모의투자 처음에 돈 얼마 줘?" 같은 질문은 일반 갈래로 가는데 모델은 우리 사이트를 모르므로
네이버·증권사 모의투자 이야기를 하거나(1억 원), 스톡메이트를 "주식 커뮤니티 플랫폼"으로 지어냈다
(2026-09-22 측정, 사이트 질문 20건 중 사이트 사실대로 답한 것 0건).

그래서 세 번째 갈래를 둔다. 판별은 신호어 기반이다.
- 추가 LLM 호출이 없어 지연이 늘지 않고, 네트워크 없이 테스트할 수 있다.
- 잘못 분류돼도 괜찮도록 사이트 프롬프트는 일반 프롬프트의 상위 집합으로 만든다
  (일반 투자 질문도 그대로 답한다). 그래서 신호어는 넓게 잡는 쪽이 안전하다.

안내서(site_guide.md)는 프론트·백엔드 코드에서 확인한 사실만 담는다. 사이트 규칙이 바뀌면
이 파일만 고치면 된다. 몇천 자 수준이라 벡터 검색 없이 통째로 넣는다.

작성 기준 (2026-09-22): StockMate_Front main 95782d6, StockMate_Back main fddeab4.
- 화면과 서버가 다른 곳은 서버 동작을 따랐다. 예: 대시보드의 '정답 시 +500원/문제' 문구와 달리
  서버는 문제마다 저장된 금액을 준다(확인한 기본 문제 1~300번은 1,000원). 그래서 안내서는 "문제에 표시된 금액"으로 쓴다.
- 서버에 있어도 화면에서 쓸 수 없는 기능(지정가·예약 주문, NXT 거래, 이메일·비밀번호 찾기)은
  사용자가 할 수 없는 것으로 적었다.
"""
import re
from functools import lru_cache
from pathlib import Path

from app.schemas.chat import Message

_GUIDE_PATH = Path(__file__).with_name("site_guide.md")

# 사이트 기능·메뉴를 가리키는 신호어.
# 일반 금융 용어와 겹치는 말은 좁혀 둔다:
#   "신용등급" → 등급은 '내/학습/현재 등급', '등급 진단/재진단', '등급이 오르다' 꼴만
#   "ISA 계좌 가입" → 가입은 '회원가입'만
#   "계정과목" → 계정 뒤에 '과목'이 오면 제외
#   "PER 낮으면 좋아요?" → 좋아요는 '좋아요를/좋아요 수/좋아요순…' 꼴만
_SITE_PATTERNS = [
    r"스톡\s?메이트", r"stock\s?mate", r"사이트", r"홈페이지", r"이\s?앱", r"이\s?서비스", r"메뉴",
    r"모의\s?투자", r"가상\s?(자금|자산|머니|돈|계좌)", r"시드\s?머니", r"(초기|시작)\s?(자금|자본|금액)",
    r"예수금.{0,6}(얼마|늘|줄|받)",
    r"퀴즈", r"문제를?\s?(풀|맞히|맞추|틀리)", r"맞히면|맞추면", r"오답", r"찜", r"북마크",
    r"보상", r"리워드", r"획득\s?자금",
    r"랭킹", r"커뮤니티", r"게시판", r"게시글", r"글\s?(쓰|작성|수정|삭제|올리)", r"댓글",
    r"좋아요(를|\s?(수|순|누르|받|개))",
    r"관심\s?종목", r"알림", r"마이\s?페이지",
    r"회원\s?가입", r"탈퇴", r"로그인", r"로그아웃", r"비밀번호", r"닉네임", r"프로필", r"계정(?!\s?과목)",
    r"투자\s?성향", r"재진단", r"(성향|수준|등급)\s?(진단|검사|테스트)",
    r"(내|나의|학습|현재)\s?등급", r"등급.{0,6}(올라|오르|올리|바꾸|바뀌|정해|결정)", r"레벨",
    r"개념\s?정리", r"(학습|질문|풀이)\s?기록", r"개인\s?맞춤", r"맞춤\s?학습", r"연속\s?학습", r"미션",
    r"AI\s?(분석|설명)", r"대시보드", r"투자\s?내역",
    r"(문제|퀴즈)(를|을)?\s?(만들|생성)",
]
_SITE_RE = re.compile("|".join(f"(?:{p})" for p in _SITE_PATTERNS), re.IGNORECASE)


def is_site_question(question: str) -> bool:
    """질문이 사이트 기능·메뉴·규칙에 대한 것인지."""
    return bool(_SITE_RE.search(question or ""))


def is_site_followup(history: list[Message]) -> bool:
    """직전 사용자 질문이 사이트 질문이었는지.

    "그럼 그건 어디서 봐?" 처럼 신호어 없이 이어지는 질문을 사이트 갈래에 붙잡아 두기 위해 쓴다.
    호출부는 현재 질문에 종목이 없을 때만 이 값을 본다.
    """
    for msg in reversed(history or []):
        if msg.role == "user":
            return is_site_question(msg.content)
    return False


@lru_cache(maxsize=1)
def load_site_guide() -> str:
    return _GUIDE_PATH.read_text(encoding="utf-8").strip()
